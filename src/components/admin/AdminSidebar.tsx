export function AdminSidebar({ navigation, user }: AdminSidebarProps) {
  const pathname = usePathname();
  const [isMobileOpen, setIsMobileOpen] = React.useState(false);

  const handleSignOut = async () => {
    const supabase = createBrowserClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!
    );
    await supabase.auth.signOut();
    window.location.href = '/admin/login';
  };

  return (
    <>
      {/* Mobile Overlay */}
      <div
        className={cn(
          'fixed inset-0 z-40 bg-black/50 lg:hidden transition-opacity',
          isMobileOpen ? 'block' : 'hidden'
        )}
        onClick={() => setIsMobileOpen(false)}
        aria-hidden="true"
      />

      {/* Sidebar */}
      <aside
        className={cn(
          'fixed lg:static inset-y-0 left-0 z-50 w-64 bg-white border-r border-stone-200 transform transition-transform duration-300 ease-in-out lg:translate-x-0',
          isMobileOpen ? 'translate-x-0' : '-translate-x-full'
        )}
        aria-label="Admin navigation"
      >
        <div className="flex flex-col h-full">
          {/* Logo */}
          <div className="flex items-center gap-2 px-6 py-5 border-b border-stone-200">
            <span className="text-lg font-bold text-charcoal-900 tracking-tight">
              ADMIN
            </span>
            <span className="ml-auto px-2 py-0.5 text-xs font-medium text-stone-600 bg-stone-100 rounded-full">
              v1.0
            </span>
          </div>

          {/* Navigation */}
          <nav className="flex-1 px-4 py-6 space-y-1 overflow-y-auto" aria-label="Admin sections">
            {navigation.map((item) => {
              const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
              const Icon = icons[item.icon];
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  className={cn(
                    'flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors',
                    isActive
                      ? 'bg-charcoal-100 text-charcoal-900'
                      : 'text-stone-600 hover:bg-stone-100 hover:text-charcoal-900'
                  )}
                  aria-current={isActive ? 'page' : undefined}
                  onClick={() => setIsMobileOpen(false)}
                >
                  <span className={cn('flex-shrink-0', isActive ? 'text-charcoal-900' : 'text-stone-500')}>
                    {Icon}
                  </span>
                  {item.name}
                </Link>
              );
            })}
          </nav>

          {/* User Info & Sign Out */}
          <div className="p-4 border-t border-stone-200">
            <div className="flex items-center gap-3 mb-3">
              <div className="w-8 h-8 rounded-full bg-earth-100 flex items-center justify-center">
                <svg className="w-5 h-5 text-earth-600" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M16 7a4 4 0 11-8 0 4 4 0 018 0zM12 14a7 7 0 00-7 7h14a7 7 0 00-7-7z" />
                </svg>
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-sm font-medium text-charcoal-900 truncate">
                  {user.email || 'Admin User'}
                </p>
                <p className="text-xs text-stone-500">Administrator</p>
              </div>
            </div>
            <Button
              variant="outline"
              className="w-full"
              onClick={handleSignOut}
            >
              <span className="flex items-center justify-center gap-2">
                {icons.logout}
                <span>Sign Out</span>
              </span>
            </Button>
          </div>
        </div>
      </aside>

      {/* Mobile Menu Button */}
      <button
        type="button"
        className="lg:hidden fixed bottom-6 left-6 z-50 w-12 h-12 rounded-full bg-charcoal-900 text-white flex items-center justify-center shadow-lg"
        onClick={() => setIsMobileOpen(true)}
        aria-label="Open admin menu"
        aria-expanded={isMobileOpen}
      >
        <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 6h16M4 12h16M4 18h16" />
        </svg>
      </button>
    </>
  );
}